// Generates supabase/seed.sql from the frontend's mock catalog so the
// database starts with exactly what the UI shows.
// Run from the repo root:  node supabase/gen-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync(new URL('../web/src/data/games.ts', import.meta.url), 'utf8')
const q = (v) => (v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`)

const rows = []
for (const line of src.split('\n')) {
  const m = line.match(/^\s*\{ id: '([^']+)', title: '((?:[^'\\]|\\.)*)', platform: '([^']+)', genre: '([^']+)', year: (\d+), cover: c\('([^']+)'\), players: (\d+)(.*)\},?\s*$/)
  if (!m) continue
  const [, id, title, platform, genre, year, cover, players, rest] = m
  const file = rest.match(/file: '([^']+)'/)?.[1]
  const license = rest.match(/license: '([^']+)'/)?.[1]
  const author = rest.match(/author: '([^']+)'/)?.[1]
  const source = rest.match(/source: '([^']+)'/)?.[1]
  rows.push(`  (${[q(id), q(title), q(platform), q(genre), year, players, q(`/assets/covers/${cover}`), q(file), q(license), q(author), q(source)].join(', ')})`)
}

const featured = ['super-mario-world', 'sonic-2', 'pac-man', 'street-fighter-2']
const sql = `-- Generated by supabase/gen-seed.mjs from web/src/data/games.ts. Do not edit by hand.
insert into public.games (id, title, platform, genre, year, players, cover_url, rom_url, rom_license, publisher, source_url) values
${rows.join(',\n')}
on conflict (id) do update set
  title = excluded.title, platform = excluded.platform, genre = excluded.genre, year = excluded.year,
  players = excluded.players, cover_url = excluded.cover_url, rom_url = excluded.rom_url, rom_license = excluded.rom_license,
  publisher = excluded.publisher, source_url = excluded.source_url;

update public.games set featured = true where id in (${featured.map(q).join(', ')});
`
writeFileSync(new URL('./seed.sql', import.meta.url), sql)
console.log(`wrote supabase/seed.sql (${rows.length} games)`)
